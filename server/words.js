const WORDS = [];
for (const [category, list] of Object.entries(BANK)) {
  for (const entry of list) {
    const [word, ...aliases] = entry.split('|');
    WORDS.push({ word, aliases, category });
  }
}

// 比對答案：去掉空白與標點、英文轉小寫
const norm = s => String(s).toLowerCase().replace(/[\s\p{P}\p{S}]/gu, '');

function isCorrect(guess, w) {
  const g = norm(guess);
  return g === norm(w.word) || w.aliases.some(a => norm(a) === g);
}

// 很接近：差一個字、或猜的內容包含答案 / 被答案包含
function isClose(guess, w) {
  const g = norm(guess);
  if (!g) return false;
  return [w.word, ...w.aliases].some(ans => {
    const a = norm(ans);
    if (g.length >= 2 && (a.includes(g) || g.includes(a))) return true;
    if (g.length === a.length && a.length >= 2) {
      let diff = 0;
      for (let i = 0; i < a.length; i++) if (a[i] !== g[i]) diff++;
      return diff === 1;
    }
    return false;
  });
}

module.exports = { WORDS, isCorrect, isClose, norm };
